class ChickTalkService {
  private lastQuoteMap: Record<string, string> = {};

  /**
   * Get a random quote from category avoiding immediate duplicate repetition
   */
  public getRandomQuote(category: keyof typeof CHICK_TALKS): string {
    const list = CHICK_TALKS[category] || CHICK_TALKS.idle;
    const last = this.lastQuoteMap[category];
    const pool = list.filter((q) => q !== last);
    const chosen = pool.length > 0
      ? pool[Math.floor(Math.random() * pool.length)]
      : list[Math.floor(Math.random() * list.length)];

    this.lastQuoteMap[category] = chosen;
    return chosen;
  }
}

export const chickTalkService = new ChickTalkService();
